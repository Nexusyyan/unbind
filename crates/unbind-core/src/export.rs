use crate::models::{CoreResult, ExportFormat, InstalledApp};
use chrono::Local;
use std::fs;
use std::path::Path;

/// Export the installed applications list to a standalone HTML report, Excel-friendly UTF-8 BOM CSV,
/// or structured JSON file.
pub fn export_apps_list(
    apps: &[InstalledApp],
    format: ExportFormat,
    output_path: &Path,
) -> CoreResult<usize> {
    match format {
        ExportFormat::Json => {
            let json = serde_json::to_string_pretty(apps)?;
            fs::write(output_path, json)?;
        }
        ExportFormat::Csv => {
            let mut out = String::from("\u{FEFF}Name,Publisher,Version,Install Date,Size (MB),Type,Scope,Architecture,Install Location,Registry Key\r\n");
            for app in apps {
                let size_mb = if app.estimated_size_kb > 0 {
                    format!("{:.2}", app.estimated_size_kb as f64 / 1024.0)
                } else {
                    String::new()
                };
                out.push_str(&format!(
                    "{},{},{},{},{},{:?},{:?},{:?},{},{}\r\n",
                    csv_escape(&app.name),
                    csv_escape(&app.publisher),
                    csv_escape(&app.version),
                    csv_escape(&app.install_date),
                    size_mb,
                    app.kind,
                    app.scope,
                    app.arch,
                    csv_escape(&app.install_location),
                    csv_escape(&app.registry_key),
                ));
            }
            fs::write(output_path, out)?;
        }
        ExportFormat::Html => {
            let generated = Local::now().format("%Y-%m-%d %H:%M:%S").to_string();
            let total_kb: u64 = apps.iter().map(|a| a.estimated_size_kb).sum();
            let total_gb = total_kb as f64 / (1024.0 * 1024.0);
            let mut rows = String::with_capacity(apps.len() * 256);
            for (idx, app) in apps.iter().enumerate() {
                let size_text = if app.estimated_size_kb >= 1024 {
                    format!("{:.1} MB", app.estimated_size_kb as f64 / 1024.0)
                } else if app.estimated_size_kb > 0 {
                    format!("{} KB", app.estimated_size_kb)
                } else {
                    "-".to_string()
                };
                rows.push_str(&format!(
                    "<tr><td>{}</td><td><strong>{}</strong></td><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td>{:?}</td><td class=\"mono\">{}</td></tr>\n",
                    idx + 1,
                    html_escape(&app.name),
                    html_escape(&app.publisher),
                    html_escape(&app.version),
                    html_escape(&app.install_date),
                    size_text,
                    app.kind,
                    html_escape(&app.install_location),
                ));
            }
            let html = format!(
                r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>Unbind - Installed Applications Report</title>
<style>
  body {{ font-family: "Segoe UI Variable Text", "Segoe UI", sans-serif; margin: 32px; background: #f9f9fa; color: #1a1a1d; }}
  .card {{ background: #ffffff; border: 1px solid rgba(0,0,0,0.06); border-radius: 14px; padding: 24px; }}
  h1 {{ margin: 0 0 6px; font-size: 20px; font-weight: 500; letter-spacing: -0.015em; }}
  .meta {{ color: #6e6e77; font-size: 13px; margin-bottom: 20px; font-variant-numeric: tabular-nums; }}
  table {{ width: 100%; border-collapse: collapse; font-size: 13px; }}
  th {{ text-align: left; padding: 10px 12px; border-bottom: 1px solid rgba(0,0,0,0.08); color: #9a9aa3; font-size: 11.5px; font-weight: 500; }}
  td {{ padding: 9px 12px; border-bottom: 1px solid rgba(0,0,0,0.05); vertical-align: top; font-variant-numeric: tabular-nums; }}
  tr:hover td {{ background: #f2f2f4; }}
  .mono {{ font-family: Consolas, monospace; font-size: 12px; color: #6e6e77; word-break: break-all; }}
</style>
</head>
<body>
<div class="card">
  <h1>Installed Applications Report</h1>
  <div class="meta">Generated by Unbind on {} | {} programs | Estimated {:.2} GB</div>
  <table>
    <thead>
      <tr><th>#</th><th>Name</th><th>Publisher</th><th>Version</th><th>Installed</th><th>Size</th><th>Type</th><th>Location</th></tr>
    </thead>
    <tbody>
      {}
    </tbody>
  </table>
</div>
</body>
</html>"#,
                generated,
                apps.len(),
                total_gb,
                rows
            );
            fs::write(output_path, html)?;
        }
    }
    Ok(apps.len())
}

fn csv_escape(s: &str) -> String {
    if s.contains(',') || s.contains('"') || s.contains('\n') || s.contains('\r') {
        format!("\"{}\"", s.replace('"', "\"\""))
    } else {
        s.to_string()
    }
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::{AppKind, Arch, InstallScope, PackageManagerKind};
    use tempfile::tempdir;

    #[test]
    fn test_export_all_formats() {
        let dir = tempdir().unwrap();
        let apps = vec![InstalledApp {
            id: "1".into(),
            name: "7-Zip, \"Test\"".into(),
            publisher: "Igor Pavlov".into(),
            version: "24.08".into(),
            install_date: "2026-01-01".into(),
            estimated_size_kb: 5120,
            install_location: "C:\\Program Files\\7-Zip".into(),
            uninstall_string: String::new(),
            quiet_uninstall_string: String::new(),
            display_icon: String::new(),
            url_info_about: String::new(),
            registry_key: String::new(),
            registry_hive: String::new(),
            registry_view: String::new(),
            product_code: String::new(),
            package_full_name: String::new(),
            package_family_name: String::new(),
            kind: AppKind::Win32,
            scope: InstallScope::Machine,
            arch: Arch::X64,
            is_system_component: false,
            is_windows_update: false,
            is_valid_entry: true,
            has_uninstaller: true,
            tracked_trace_id: None,
            package_manager: PackageManagerKind::None,
            size_measured: false,
        }];

        for (fmt, name) in [
            (ExportFormat::Json, "out.json"),
            (ExportFormat::Csv, "out.csv"),
            (ExportFormat::Html, "out.html"),
        ] {
            let p = dir.path().join(name);
            let n = export_apps_list(&apps, fmt, &p).unwrap();
            assert_eq!(n, 1);
            assert!(p.exists());
            assert!(fs::metadata(&p).unwrap().len() > 20);
        }
    }
}
